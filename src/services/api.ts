// Get detailed information about a specific model
export const fetchModelDetails = async (modelName: string): Promise<any> => {
  try {
    const endpoint = '/show';
    const response = await api.post(endpoint, {
      name: modelName
    }, {
      headers: getHeaders(),
    });
    
    if (response.data) {
      return response.data;
    }
    
    return null;
  } catch (error) {
    console.error(`Error fetching details for model ${modelName}:`, error);
    return null;
  }
};

// =============================================================================
// PDF FIGURE DESCRIPTION (vision-model captioning of extracted figures)
// =============================================================================
//
// After the Python backend extracts figure regions from a PDF, we ask the
// CURRENT vision-capable model to write a short textual description of each
// figure. That description is then stored on the FileAttachment (in
// `imageMeta[].description`) and inlined into the LLM's view of the PDF on
// every subsequent turn — so even after a model switch to a text-only model,
// the model still "knows" what each figure shows.
//
// We deliberately use Ollama's /api/generate (single-shot) instead of /api/chat
// to keep this call cheap and stateless — we only need one short reply per
// image, no chat history.

export interface DescribePdfImageOptions {
  /** PDF page number the figure appears on (used in the prompt). */
  page?: number;
  /** Human-readable label parsed from the caption (e.g. "Figure 3"). */
  label?: string | null;
  /** Caption text exactly as it appears in the PDF, if any. */
  caption?: string | null;
  /** Abort signal so the caller can cancel a long-running description. */
  signal?: AbortSignal;
  /** Override the per-call timeout (ms). Defaults to 60_000. */
  timeoutMs?: number;
}

/**
 * Ask `modelId` to describe a single PDF figure given as a data URI or raw
 * base64. Returns a short (1–3 sentence) description string, or `null` on
 * failure / abort. Does NOT throw — failure is non-fatal so PDF upload
 * doesn't break when the model is slow or unavailable.
 *
 * The CALLER is responsible for ensuring `modelId` actually supports vision
 * (via the `capabilities` field from /api/show). When the user's current
 * model is text-only this function should not be called at all.
 */
export const describePdfImage = async (
  modelId: string,
  imageDataOrUri: string,
  opts: DescribePdfImageOptions = {},
): Promise<string | null> => {
  if (!modelId || !imageDataOrUri) return null;
  // Ollama expects raw base64 (no data: prefix) in the `images` array.
  const cleanBase64 = imageDataOrUri.includes(',')
    ? imageDataOrUri.split(',')[1]
    : imageDataOrUri;
  if (!cleanBase64) return null;

  // Build a tight prompt: we give the model the caption (when present) so it
  // anchors the description to what the author called it, but we ask for an
  // independent visual summary it could write WITHOUT the caption. The
  // resulting text is what a text-only LLM downstream will read instead of
  // the actual pixels, so it needs to be self-contained.
  const pageStr = opts.page != null ? ` (page ${opts.page})` : '';
  const labelStr = opts.label ? `“${opts.label}”` : 'this figure';
  const captionLine = opts.caption
    ? `\nThe PDF caption for this figure is: "${opts.caption}".`
    : '';
  const prompt =
    `You are describing a single figure extracted from a PDF document so that` +
    ` a text-only language model can later answer questions about it without` +
    ` seeing the image.\n\n` +
    `Write a concise, factual description of ${labelStr}${pageStr} in 2–4` +
    ` sentences. Cover:\n` +
    `  • What KIND of visual it is (chart, diagram, photo, schematic, table-like,` +
    ` micrograph, plot, equation, etc.).\n` +
    `  • The main subject / what is being shown.\n` +
    `  • Any axes, labels, panels, legends, units, comparisons or trends you can` +
    ` actually read in the image.\n` +
    `  • Notable colors, groupings, or visual structure that would matter for` +
    ` interpreting the figure.\n` +
    `Avoid speculating beyond what is visible. Do NOT repeat the caption` +
    ` verbatim. Reply with the description only — no preamble, no markdown` +
    ` headers, no bullet points.` +
    captionLine;

  // Per-image timeout. We default to 5 minutes because the FIRST call for
  // a session also has to load the vision model into VRAM (cold start can
  // be 30–60 s on its own for 12B–27B class models). Subsequent calls are
  // much faster. The caller can override via opts.timeoutMs.
  const timeoutMs = opts.timeoutMs ?? 300_000;
  const controller = new AbortController();
  // Chain external abort signal into our own controller.
  if (opts.signal) {
    if (opts.signal.aborted) return null;
    opts.signal.addEventListener('abort', () => controller.abort(), { once: true });
  }
  const timer = setTimeout(() => controller.abort(), timeoutMs);

  const t0 = (typeof performance !== 'undefined' ? performance.now() : Date.now());
  console.info(
    `[describePdfImage] → POST /generate model=${modelId} ` +
    `page=${opts.page ?? '?'} label=${opts.label ?? 'none'} ` +
    `imgBytes≈${Math.round((cleanBase64.length * 3) / 4)} ` +
    `(timeout=${timeoutMs}ms)`,
  );

  try {
    const response = await api.post(
      '/generate',
      {
        model: modelId,
        prompt,
        images: [cleanBase64],
        stream: false,
        // Keep the reply short — we want ~80–150 tokens.
        options: {
          num_predict: 220,
          temperature: 0.2,
        },
        // Keep the model resident between figures so we don't reload weights
        // 9× in a row for a 9-figure paper.
        keep_alive: '10m',
      },
      {
        headers: getHeaders(),
        signal: controller.signal,
        // Axios timeout as a backup; the AbortController is primary.
        timeout: timeoutMs + 5_000,
      },
    );
    const dt = Math.round(((typeof performance !== 'undefined' ? performance.now() : Date.now()) - t0));
    const text: string | undefined = response?.data?.response;
    const evalCount = response?.data?.eval_count;
    const totalDuration = response?.data?.total_duration;
    console.info(
      `[describePdfImage] ← ${dt}ms model=${modelId} ` +
      `status=${response?.status} eval_count=${evalCount ?? '?'} ` +
      `total_duration=${totalDuration ?? '?'} ` +
      `bytes=${text ? text.length : 0}`,
    );
    if (!text) {
      console.warn(`[describePdfImage] empty response.response from ${modelId}`, response?.data);
      return null;
    }
    // Strip surrounding whitespace and any accidental "Description:" prefix.
    const cleaned = text
      .trim()
      .replace(/^(description|figure description|summary)\s*:\s*/i, '')
      .trim();
    return cleaned || null;
  } catch (err: any) {
    const dt = Math.round(((typeof performance !== 'undefined' ? performance.now() : Date.now()) - t0));
    if (controller.signal.aborted) {
      console.warn(
        `[describePdfImage] aborted/timeout after ${dt}ms for model ${modelId}`,
      );
    } else {
      // Surface as much detail as axios gives us so the user can see
      // whether the call hit Ollama at all (network/CORS/404 vs 500).
      const status = err?.response?.status;
      const respData = err?.response?.data;
      console.error(
        `[describePdfImage] failed after ${dt}ms for model ${modelId}: ` +
        `status=${status ?? 'no-response'} message=${err?.message || err}`,
        respData ?? '',
      );
    }
    return null;
  } finally {
    clearTimeout(timer);
  }
};



