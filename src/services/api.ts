// Fetch available models
export const fetchModels = async (): Promise<ModelType[]> => {
  try {
    const endpoint = '/tags';
    const response = await api.get(endpoint, {
      headers: getHeaders(),
    });
    
if (response.data && response.data.models) {
      // Filter out embedding models (nomic, embed) - these are not for chat
      const chatModels = response.data.models.filter((model: any) => {
        const modelName = model.name.toLowerCase();
        return !modelName.includes('nomic') && !modelName.includes('embed');
      });
      
      return chatModels.map((model: any) => ({
        id: model.name,
        name: model.name,
        size: model.size,
        quantization: model.name.includes('q') ? model.name.split('-').pop() : undefined,
        isDefault: false,
      }));
    }
    
    // Return empty array when API is not available
    return [];
  } catch (error) {
    console.error('Error fetching models:', error);
    
    // Return empty array when there's an error
    return [];
  }
};

