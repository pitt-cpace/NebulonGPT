/**
 * Render the AI-generated descriptions of PDF figures into a markdown-style
 * block we can append to the user message content. This is what makes the
 * descriptions actually reach the LLM on every turn (even if the user later
 * switches to a text-only model). We label items by page + caption-label
 * when we have one, so the LLM can cross-reference with the document's own
 * "Fig. 1", "Table 2" references.
 *
 * Output looks like:
 *
 *   --- Figures in "paper.pdf" (described by gemma3:latest) ---
 *   • Figure 1 (page 2): The figure compares three protein-LM architectures…
 *   • Figure 2 (page 4): A line chart with x-axis "epoch" 0–50…
 *   • Table 1 (page 3): A 6x9 comparison table contrasting SWING vs five baselines…
 *   ---
 *
 * Items without a `description` are still listed (with their caption and
 * page) so the LLM at least knows the figure exists. Items missing both
 * `description` AND `caption` are skipped — they'd add zero information.
 */
export const formatPdfImageMetaForLlm = (
  pdfName: string,
  metas: PdfImageMeta[],
): string => {
  if (!Array.isArray(metas) || metas.length === 0) return '';
  const usefulMetas = metas.filter(
    (m) => (m && (m.description || m.caption))
  );
  if (usefulMetas.length === 0) return '';
  // If any of the items has a `describedBy`, surface that model name in the
  // header so the receiving LLM knows where these descriptions came from.
  const describers = Array.from(
    new Set(
      usefulMetas
        .map((m) => m.describedBy)
        .filter((s): s is string => !!s)
    )
  );
  const headerSuffix = describers.length > 0
    ? ` (figure descriptions generated by ${describers.join(', ')})`
    : '';
  const lines: string[] = [];
  lines.push(`\n\n--- Figures in "${pdfName}"${headerSuffix} ---`);
  for (const m of usefulMetas) {
    const head = m.label
      ? `${m.label} (page ${m.page})`
      : `Figure ${m.index} (page ${m.page})`;
    const captionPart = m.caption ? ` — caption: "${m.caption}"` : '';
    if (m.description) {
      lines.push(`• ${head}${captionPart}\n   ${m.description.replace(/\n+/g, ' ')}`);
    } else {
      // No AI description was produced (e.g. text-only current model at
      // extraction time, or the describer failed). At minimum convey the
      // caption + label so the main LLM doesn't think the figure is empty.
      lines.push(`• ${head}${captionPart}\n   (no visual description available)`);
    }
  }
  lines.push('---');
  return lines.join('\n');
};


// Function to get the base URL, checking localStorage first
const getBaseURL = (): string => {
  // Check if user has set a custom Ollama API URL
  const customUrl = localStorage.getItem('ollamaApiUrl');
  if (customUrl && customUrl.trim() !== '') {
    // Custom URL is already normalized with /api appended
    console.log(`Using custom Ollama URL from settings: ${customUrl.trim()}`);
    return customUrl.trim();
  }
  
  // Electron app: Direct connection to Ollama
  if (isElectron()) {
    const ollamaUrl = process.env.REACT_APP_OLLAMA_URL || 'http://localhost:11434';
    console.log(`[Electron] Using direct Ollama URL: ${ollamaUrl}/api`);
    return `${ollamaUrl}/api`;
  }
  
  // Browser/Docker: Use nginx proxy (respects runtime OLLAMA_URL env var)
  console.log('[Browser/Docker] Using nginx proxy: /api/ollama');
  return '/api/ollama';
};

// Function to get the API key from localStorage
const getApiKey = (): string => {
  return localStorage.getItem('ollamaApiKey') || '';
};

// Function to get headers with optional API key
const getHeaders = (): Record<string, string> => {
  const headers: Record<string, string> = {
    'Content-Type': 'application/json',
  };
  
  const apiKey = getApiKey();
  if (apiKey && apiKey.trim() !== '') {
    headers['Authorization'] = `Bearer ${apiKey.trim()}`;
  }
  
  return headers;
};

// Get the initial base URL
let baseURL = getBaseURL();

// Export function to get Ollama base URL (without /api suffix)
export const getOllamaBaseUrl = (): string => {
  // Check if user has set a custom Ollama API URL
  const customUrl = localStorage.getItem('ollamaApiUrl');
  if (customUrl && customUrl.trim() !== '') {
    // Remove /api suffix if present
    const url = customUrl.trim();
    return url.endsWith('/api') ? url.slice(0, -4) : url;
  }
  
  // Electron app: Direct connection to Ollama
  if (isElectron()) {
    const ollamaUrl = process.env.REACT_APP_OLLAMA_URL || 'http://localhost:11434';
    return ollamaUrl;
  }
  
  // Browser/Docker: Use nginx proxy
  return '/api/ollama';
};

